using namespace std;

inline int read() {
    char ch = getchar();
    while (ch == ' ' || ch == '\n') ch = getchar();
    if (ch == EOF) return EOF;
    int s = 1;
    while (ch < '0' || '9' < ch) {
        if (ch == '-') s = -1;
        ch = getchar();
    }
    int r = 0;
    while ('0' <= ch && ch <= '9') r = r * 10 + ch - '0', ch = getchar();
    return r * s;
}

inline string read_line() {
    string r = "";
    char ch = getchar();
    while (ch != '\n' && ch != EOF) r += ch, ch = getchar();
    return r;
}

void write(int x) {
    if (x < 0) {
        putchar('-');
        x = -x;
    }
    if (x > 9) write(x / 10);
    putchar(x % 10 + '0');
}

inline void write_line(string str) {
    for (int i = 0; i < str.length(); i++) putchar(str[i]);
}

signed main() {
    int n = read(), k = read();
	int r = read(), s = read(), p = read();
	string machine = read_line();
	vector<bool> draw(n, false);
	int ans = 0;
	for (int i = 0; i < n; i++) {
		if (i < k || machine[i - k] != machine[i] || draw[i - k]) {
			ans += machine[i] == 'r' ? p : machine[i] == 's' ? r : s;
		} else {
			draw[i] = true;
		}
	}
	write(ans);
    return 0;
}